import type { SupabaseClient } from "@supabase/supabase-js";

// Compensation for a failed roster apply. Auth and application tables are not one transaction,
// so accounts created by the batch must be removed again. Every deletion is checked; nothing is
// reported as cleaned unless it was verified (AC-AUTH-002).
export type CompensationDeps = {
  admin: SupabaseClient;
  // Test seams. Defaults call the Supabase Auth admin API.
  deleteAuthUser?: (id: string) => Promise<{ message: string } | null>;
  listAuthUserIdsByEmail?: (emails: ReadonlySet<string>) => Promise<string[]>;
  authUserExists?: (id: string) => Promise<boolean>;
  retryDelayMs?: number;
};

export type CompensationResult = { removed: string[]; remaining: string[]; locked: number };

const ATTEMPTS = 3;
const MAX_LIST_PAGES = 20;

async function defaultListByEmail(admin: SupabaseClient, emails: ReadonlySet<string>): Promise<string[]> {
  const found: string[] = [];
  for (let page = 1; page <= MAX_LIST_PAGES; page += 1) {
    const { data, error } = await admin.auth.admin.listUsers({ page, perPage: 200 });
    if (error) throw new Error(`listUsers failed: ${error.message}`);
    for (const user of data.users) if (user.email && emails.has(user.email)) found.push(user.id);
    if (data.users.length < 200) break;
  }
  return found;
}

export async function compensateBatch(deps: CompensationDeps, createdIds: string[], attemptedEmails: string[]): Promise<CompensationResult> {
  const { admin } = deps;
  const remove = deps.deleteAuthUser ?? (async (id: string) => (await admin.auth.admin.deleteUser(id)).error);
  const exists =
    deps.authUserExists ??
    (async (id: string) => {
      const { data } = await admin.auth.admin.getUserById(id);
      return Boolean(data?.user);
    });
  const delay = deps.retryDelayMs ?? 250;

  // A create call can succeed on the provider and still fail on the way back, so the id is
  // unknown. The internal emails are generated by us, so look those accounts up as well.
  const ids = new Set(createdIds);
  try {
    for (const id of await (deps.listAuthUserIdsByEmail ?? ((e) => defaultListByEmail(admin, e)))(new Set(attemptedEmails))) ids.add(id);
  } catch {
    // Listing failed: continue with the ids we know; verification below still covers them.
  }

  const removed: string[] = [];
  const remaining: string[] = [];
  for (const id of ids) {
    let error: { message: string } | null = null;
    for (let attempt = 1; attempt <= ATTEMPTS; attempt += 1) {
      try {
        error = await remove(id);
      } catch (thrown) {
        error = { message: thrown instanceof Error ? thrown.message : "delete threw" };
      }
      if (!error) break;
      if (attempt < ATTEMPTS && delay > 0) await new Promise((resolve) => setTimeout(resolve, delay * attempt));
    }
    // Trust nothing: confirm the Auth user and the cascaded profile are really gone.
    let gone = !error;
    if (gone) {
      try {
        if (await exists(id)) gone = false;
      } catch {
        gone = false;
      }
    }
    if (gone) {
      const { count } = await admin.from("profiles").select("id", { count: "exact", head: true }).eq("id", id);
      if ((count ?? 0) > 0) gone = false;
    }
    (gone ? removed : remaining).push(id);
  }

  // Anything that could not be removed must not stay usable: lock the profile and end sessions.
  let locked = 0;
  if (remaining.length > 0) {
    const { data } = await admin.from("profiles").update({ status: "locked" }).in("id", remaining).select("id");
    locked = data?.length ?? 0;
    for (const id of remaining) await admin.rpc("revoke_user_sessions", { p_user_id: id });
  }
  return { removed, remaining, locked };
}
